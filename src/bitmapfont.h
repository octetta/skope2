// ---------------------------------------------------------------------------
// Atlas texture (one global; call bf_init / bf_uninit around window lifetime)
// ---------------------------------------------------------------------------

// Atlas layout: 96 glyphs in a row, each BF_W wide, BF_H tall
// Total size: 96*8 = 768 × 8 pixels, RGBA
#define BF_ATLAS_W (BF_COUNT * BF_W)  // 768
#define BF_ATLAS_H  BF_H              // 8

static Texture2D g_bf_tex;
static int       g_bf_ready = 0;

// Convert the 1-bit glyph data into a white RGBA atlas.
// The tint color is applied per-draw-call, so we just bake white pixels.
static void bf_init(void) {
  if (g_bf_ready) return;

  // Allocate pixels: RGBA, white where bit is set, transparent where not.
  unsigned char *px = (unsigned char *)calloc(BF_ATLAS_W * BF_ATLAS_H * 4, 1);
  if (!px) return;

  for (int g = 0; g < BF_COUNT; g++) {
    for (int row = 0; row < BF_H; row++) {
      unsigned char byte = kBF_Glyphs[g][row];
      for (int col = 0; col < BF_W; col++) {
        int bit = (byte >> (7 - col)) & 1;
        int px_x = g * BF_W + col;
        int px_y = row;
        int idx  = (px_y * BF_ATLAS_W + px_x) * 4;
        px[idx + 0] = 255;        // R
        px[idx + 1] = 255;        // G
        px[idx + 2] = 255;        // B
        px[idx + 3] = bit ? 255 : 0;  // A
      }
    }
  }

  Image img = {
    .data    = px,
    .width   = BF_ATLAS_W,
    .height  = BF_ATLAS_H,
    .mipmaps = 1,
    .format  = PIXELFORMAT_UNCOMPRESSED_R8G8B8A8,
  };
  g_bf_tex   = LoadTextureFromImage(img);
  // Point filtering — keeps pixels sharp at integer scales.
  SetTextureFilter(g_bf_tex, TEXTURE_FILTER_POINT);
  free(px);
  g_bf_ready = 1;
}

static void bf_uninit(void) {
  if (!g_bf_ready) return;
  UnloadTexture(g_bf_tex);
  g_bf_ready = 0;
}

// ---------------------------------------------------------------------------
// Rendering helpers
// ---------------------------------------------------------------------------

// Choose the best integer pixel scale so glyph height ≤ max_h.
static inline int bf_scale_for_height(int max_h) {
  int s = max_h / BF_H;
  return s < 1 ? 1 : s;
}

// Pixel width of a string at integer scale s (includes 1px gap between chars)
static inline int bf_measure(const char *txt, int s) {
  if (!txt || !*txt) return 0;
  int n = 0;
  while (*txt++) n++;
  return n * (BF_W * s) + (n > 1 ? (n - 1) * s : 0);
}

// Pixel height at scale s
static inline int bf_char_h(int s) { return BF_H * s; }

// Draw a single character. Returns x advance (px).
static inline int bf_char(char c, int x, int y, int s, Color col) {
  if (!g_bf_ready) return BF_W * s + s;
  int idx = (unsigned char)c - BF_FIRST;
  if (idx < 0 || idx >= BF_COUNT) idx = 0;  // map unknowns to space

  Rectangle src  = { (float)(idx * BF_W), 0, (float)BF_W, (float)BF_H };
  Rectangle dest = { (float)x, (float)y,  (float)(BF_W * s), (float)(BF_H * s) };
  DrawTexturePro(g_bf_tex, src, dest, (Vector2){0,0}, 0.0f, col);
  return BF_W * s + s;  // glyph width + 1px gap (scaled)
}

// Draw a string. Uppercase conversion is optional: pass upper=1 to force
// all lowercase to uppercase (matching the Tek scope readout style).
static void bf_text_ex(const char *txt, int x, int y, int s, Color col,
                        int force_upper) {
  if (!txt || !g_bf_ready) return;
  int cx = x;
  while (*txt) {
    char c = *txt++;
    if (force_upper && c >= 'a' && c <= 'z') c = (char)(c - 32);
    cx += bf_char(c, cx, y, s, col);
  }
}

// Convenience: draw with forced uppercase (scope readout style)
static inline void bf_text(const char *txt, int x, int y, int s, Color col) {
  bf_text_ex(txt, x, y, s, col, 1);
}

// Convenience: draw mixed case (for help text etc.)
static inline void bf_text_mixed(const char *txt, int x, int y, int s, Color col) {
  bf_text_ex(txt, x, y, s, col, 0);
}

