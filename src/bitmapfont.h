// bitmapfont.h
//
// Minimal IBM PC 8×8 CGA/MDA bitmap font renderer for raylib.
//
// The glyph data is the public domain IBM PC technical reference
// character set (1981), covering ASCII 32-127.  Each glyph is 8×8
// pixels stored as 8 bytes, one byte per row, MSB = leftmost pixel.
//
// On first call to bf_init() the glyphs are baked into a small
// RGBA raylib Texture2D (a single 96×8 pixel atlas).  Rendering is
// one DrawTexturePro call per character — zero font rasterisation,
// no GPU shader changes, negligible CPU cost.
//
// Scaling:  the font renders at a whole-pixel scale factor (×1, ×2, ×3 …)
// so glyphs always stay sharp.  bf_scale_for_height(h) returns the
// largest integer scale whose pixel height ≤ h.
//
// Usage:
//   bf_init();                              // call once after InitWindow
//   bf_text("HELLO", 10, 10, 2, WHITE);    // scale 2 → 16×16 px glyphs
//   int w = bf_measure("HELLO", 2);        // pixel width at that scale
//   bf_text_wrap(s, x, y, scale, col, maxw); // word-wrap into maxw px
//   bf_uninit();                            // call before CloseWindow
//
// Alpha:  the color's alpha is applied per-glyph via DrawTexturePro tint.

